#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum LexError {
    #[error("the lexer trapped and its instance was discarded")]
    Trap,
    #[error("the lexer instance trapped earlier and can no longer run")]
    Poisoned,
    #[error("staging {requested} bytes would take the lexer past its {limit}-byte memory ceiling")]
    MemoryLimit { requested: usize, limit: usize },
    #[error("the lexer returned a pointer outside its memory")]
    OutOfBounds,
    #[error("the lexer instance could not be allocated")]
    Allocation,
    #[error("byte range {start}..{end} is not a valid edit range of the document")]
    InvalidRange { start: usize, end: usize },
    #[error("{0} bytes does not fit the lexer's 32-bit offsets")]
    TooLarge(usize),
}

fn status(code: i32, requested: usize, limit: usize) -> Result<(), LexError> {
    match code {
        ffi::OK => Ok(()),
        ffi::TRAP => Err(LexError::Trap),
        ffi::POISONED => Err(LexError::Poisoned),
        ffi::MEMORY_LIMIT => Err(LexError::MemoryLimit { requested, limit }),
        ffi::ALLOCATION => Err(LexError::Allocation),
        _ => Err(LexError::OutOfBounds),
    }
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use sha2::{Digest, Sha256};

    fn manifest_files() -> Vec<(String, String)> {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let manifest = std::fs::read_to_string(root.join("c/MANIFEST.toml")).expect("the manifest");
        let mut files = Vec::new();
        let mut path = None;
        for line in manifest.lines() {
            if let Some(value) = line
                .strip_prefix("path = \"")
                .and_then(|rest| rest.strip_suffix('"'))
            {
                path = Some(value.to_owned());
            } else if let Some(value) = line
                .strip_prefix("sha256 = \"")
                .and_then(|rest| rest.strip_suffix('"'))
            {
                files.extend(path.take().map(|path| (path, value.to_owned())));
            }
        }
        files
    }

    #[test]
    fn every_vendored_file_matches_the_hash_its_manifest_records() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let files = manifest_files();
        assert_eq!(files.len(), 14, "{files:?}");
        for (path, expected) in files {
            let bytes = std::fs::read(root.join(&path)).unwrap_or_else(|err| {
                assert_eq!(
                    Some(err.to_string()),
                    None,
                    "{path} is listed in MANIFEST.toml but cannot be read"
                );
                Vec::new()
            });
            let found: String = Sha256::digest(&bytes)
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect();
            assert_eq!(found, expected, "{path} no longer matches MANIFEST.toml: regenerate it with scripts/sync-pierre-highlights.sh");
        }
    }

    #[test]
    fn the_generated_tables_name_the_pinned_package() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let manifest = std::fs::read_to_string(root.join("c/MANIFEST.toml")).expect("the manifest");
        assert!(manifest.contains(&format!("version = \"{}\"", super::PACKAGE_VERSION)));
        assert!(manifest.contains(&format!("wasm_sha256 = \"{}\"", super::WASM_SHA256)));
        let banner =
            std::fs::read_to_string(root.join("c/generated/highlights.h")).expect("the header");
        assert!(banner.starts_with(&format!(
            "/* Generated by scripts/sync-pierre-highlights from @pierre/highlights {} (highlights.wasm sha256 {}). Do not edit. */\n",
            super::PACKAGE_VERSION,
            super::WASM_SHA256
        )));
    }
}
